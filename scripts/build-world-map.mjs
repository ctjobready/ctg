#!/usr/bin/env node
/**
 * Natural Earth 110m land (public domain, via world-atlas) → equirectangular SVG path, integer
 * coordinates, relative commands → src/data/world-land.ts. Run: node scripts/build-world-map.mjs
 * Projection: x = (lon + 180) / 360 * 1000 ; y = (84 - lat) / 144 * 500   (lat 84°N … 60°S)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topo, topo.objects.land);
const W = 1000, H = 500, LAT_TOP = 84, LAT_SPAN = 144;
const px = (lon) => Math.round(((lon + 180) / 360) * W);
const py = (lat) => Math.round(((LAT_TOP - lat) / LAT_SPAN) * H);

let d = '';
const polys = land.geometry ? [land.geometry] : land.features.map((f) => f.geometry);
for (const g of polys) {
  const rings = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const poly of rings) {
    const ring = poly[0]; // outer ring only (110m has no relevant holes at this scale)
    const pts = [];
    for (const [lon, lat] of ring) {
      const p = [px(lon), py(lat)];
      const last = pts[pts.length - 1];
      if (!last || last[0] !== p[0] || last[1] !== p[1]) pts.push(p);
    }
    if (pts.length < 4) continue;
    if (pts.every(([, y]) => y > H + 5)) continue; // skip Antarctica (below the crop)
    let cx = pts[0][0], cy = pts[0][1];
    d += `M${cx} ${cy}`;
    let seg = '';
    for (let i = 1; i < pts.length; i++) {
      const dx = pts[i][0] - cx, dy = pts[i][1] - cy;
      seg += `${seg ? ' ' : ''}${dx} ${dy}`;
      cx = pts[i][0]; cy = pts[i][1];
    }
    d += `l${seg}z`;
  }
}
const out = `// GENERATED by scripts/build-world-map.mjs from Natural Earth 110m land (public domain, via world-atlas).
// Equirectangular, viewBox 0 0 ${W} ${H}; lat ${LAT_TOP}°N → ${LAT_TOP - LAT_SPAN}°S. Do not edit.
export const WORLD_W = ${W};
export const WORLD_H = ${H};
export const LAT_TOP = ${LAT_TOP};
export const LAT_SPAN = ${LAT_SPAN};
export const WORLD_LAND_PATH = ${JSON.stringify(d)};
`;
writeFileSync(new URL('../src/data/world-land.ts', import.meta.url), out);
console.log('world-land.ts bytes:', out.length);
